import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
	NATIVE_BRIDGE_CAPABILITY_PLATFORMS,
	NATIVE_BRIDGE_CLIENT_METHODS,
} from '../packages/types/typings/native-capability-hosts';
import { NATIVE_BRIDGE_METHOD_CAPABILITIES } from '../packages/types/typings/native-methods';
import { ROOT } from './workspaces';

/** A file the generator writes, by its path from the repository root. */
export type GeneratedFile = { path: string; content: string };

type Binding = { capability: string; nameSpace: string; methods: string[] };

const PLATFORMS = ['ios', 'android'] as const;

// Wrapped to the loader's 100-column clang-format limit.
const BANNER = `// Generated by scripts/generate-native-capabilities.ts - DO NOT EDIT.
// Edit packages/types/typings/native-methods.ts or native-capability-hosts.ts, then run
// \`bun run generate-native-capabilities\`.`;

const CPP_PLATFORM_LISTS: Record<(typeof PLATFORMS)[number], string> = {
	ios: 'kIOSNativePluginCapabilities',
	android: 'kAndroidNativePluginCapabilities',
};

/** The generated TypeScript Capability lists the client, contracts and SDK read. */
export const TYPES_OUTPUT = 'packages/types/typings/native-capabilities.gen.ts';

/** The generated C++ Capability bindings the loader checks its bridges against. */
export const LOADER_OUTPUT = 'packages/loader/core/include/NativeCapabilityTable.h';

function capabilities(): string[] {
	return Object.keys(NATIVE_BRIDGE_CAPABILITY_PLATFORMS);
}

function platformCapabilities(platform: (typeof PLATFORMS)[number]): string[] {
	return Object.entries(NATIVE_BRIDGE_CAPABILITY_PLATFORMS)
		.filter(([, platforms]) => platforms.some((candidate) => candidate === platform))
		.map(([capability]) => capability);
}

function bindings(): Binding[] {
	const clientMethods = new Set<string>(NATIVE_BRIDGE_CLIENT_METHODS);
	const entries = Object.entries(NATIVE_BRIDGE_METHOD_CAPABILITIES);

	return capabilities().map((capability) => {
		const paths = entries.filter(([, owner]) => owner === capability).map(([path]) => path);
		const nameSpaces = new Set(paths.map((path) => path.split('.')[0] ?? ''));
		const [nameSpace = ''] = nameSpaces;

		if (nameSpaces.size !== 1) {
			throw new Error(`${capability} must bind methods of exactly one namespace`);
		}

		const methods = paths
			.filter((path) => !clientMethods.has(path))
			.map((path) => path.slice(nameSpace.length + 1));

		return { capability, nameSpace, methods };
	});
}

function quotedLines(values: readonly string[], indent: string, quote: string): string {
	return values.map((value) => `${indent}${quote}${value}${quote},\n`).join('');
}

function methodsArrayName(capability: string): string {
	const words = capability.split('.').slice(1);

	return `k${words.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join('')}Methods`;
}

function renderTypes(): string {
	const platforms = PLATFORMS.map(
		(platform) =>
			`\t${platform}: [\n${quotedLines(platformCapabilities(platform), '\t\t', "'")}\t],\n`,
	).join('');

	return `${BANNER}
import type { NativeBridgeCapability } from './native-methods';
import type { NativeBridgePlatform } from './native';

/** Every capability name a manifest may declare; an unknown name fails manifest validation. */
export const NATIVE_BRIDGE_CAPABILITIES = [
${quotedLines(capabilities(), '\t', "'")}] as const satisfies readonly NativeBridgeCapability[];

/** The capabilities each platform's loader offers; Objective-C ones are iOS only and Java ones Android only. */
export const NATIVE_BRIDGE_PLATFORM_CAPABILITIES = {
${platforms}} as const satisfies Record<NativeBridgePlatform, readonly NativeBridgeCapability[]>;
`;
}

function renderLoader(): string {
	const table = bindings();
	const methodArrays = table
		.map(
			({ capability, methods }) =>
				`inline constexpr std::array<std::string_view, ${methods.length}> ${methodsArrayName(capability)} = {\n${quotedLines(methods, '    ', '"')}};\n`,
		)
		.join('');
	const rows = table
		.map(
			({ capability, nameSpace }) =>
				`    {"${capability}", "${nameSpace}", ${methodsArrayName(capability)}},\n`,
		)
		.join('');
	const platformLists = PLATFORMS.map((platform) => {
		const listed = platformCapabilities(platform);

		return `inline constexpr std::array<const char *, ${listed.length}> ${CPP_PLATFORM_LISTS[platform]} = {\n${quotedLines(listed, '    ', '"')}};\n`;
	}).join('\n');

	return `${BANNER}
#pragma once

#include <array>
#include <span>
#include <string_view>

// clang-format off
namespace loader::native {
// A Capability and the bridge methods the loader must install under one namespace to advertise it.
struct NativeCapabilityBinding {
    std::string_view                  capability;
    std::string_view                  nameSpace;
    std::span<const std::string_view> methods;
};

${methodArrays}
inline constexpr std::array<NativeCapabilityBinding, ${table.length}> kNativeCapabilityBindings = {{
${rows}}};

${platformLists}}
// clang-format on
`;
}

/**
 * @description Renders every file generated from the native method table, without writing them.
 * @returns The files, by their path from the repository root.
 */
export function renderNativeCapabilities(): GeneratedFile[] {
	return [
		{ path: TYPES_OUTPUT, content: renderTypes() },
		{ path: LOADER_OUTPUT, content: renderLoader() },
	];
}

/**
 * @description Lists the generated files whose committed content differs from what the table renders.
 * @returns The stale files' paths, empty when every one is current.
 */
export function staleNativeCapabilityFiles(root = ROOT): string[] {
	return renderNativeCapabilities()
		.filter(({ path, content }) => {
			const file = join(root, path);

			return !existsSync(file) || readFileSync(file, 'utf8') !== content;
		})
		.map(({ path }) => path);
}

if (import.meta.main) {
	for (const { path, content } of renderNativeCapabilities()) {
		writeFileSync(join(ROOT, path), content);
		console.log(`Wrote ${path}`);
	}
}
