import { Hashing } from 'typebox/system';
import { Format } from 'typebox/format';
import type { TSchema } from 'typebox';
import { Code } from 'typebox/compile';
import Guard from 'typebox/guard';
import { Type } from 'typebox';

import { inlineExports, type TypeboxModule } from './inline';

/** One schema the client validates without shipping a validator library. */
export type ValidatorEntry = {
	/** The exported check's name, such as `isCatalogResponse`. */
	name: string;
	/** The schema to compile at generation time. */
	schema: TSchema;
	/** Type-only imports the module needs, such as `import type { catalogResponseSchema } from '...';`. */
	typeImports: string[];
	/** What the check narrows to, such as `Static<typeof catalogResponseSchema>`. */
	valueType: string;
};

/** The helpers a compiled schema needs inlined beside it. */
type Needs = {
	guard: Set<string>;
	hashing: Set<string>;
	formats: Set<string>;
	checkContext: boolean;
};

/** One schema's generated module, split into its check functions and entry call. */
type Split = {
	/** The arrow functions typebox emitted, `check_0` upward. */
	body: string;
	/** Whether the body builds a `new CheckContext(...)` per check. */
	checkContext: boolean;
};

/** One schema's compiled checks, ready to nest in the generated module. */
type Compiled = Split & {
	/** The check function the schema's `Check` returned, such as `check_0`. */
	entry: string;
	/** Expressions for the `External` array the body indexes into. */
	external: string[];
};

/**
 * @description Generates one standalone module of `(value: unknown) => value is T` checks for the
 * registry, with typebox's helpers and format checkers inlined so no validator library is imported.
 * @param entries The schemas to compile, in the order their checks are exported.
 * @returns The module source, deterministic for the same entries.
 * @throws When a schema uses `Type.Refine` or `Type.Codec`, which `Code` cannot inline faithfully.
 */
export async function generateModule(entries: ValidatorEntry[]): Promise<string> {
	const needs: Needs = {
		guard: new Set(),
		hashing: new Set(),
		formats: new Set(),
		checkContext: false,
	};
	const compiled = entries.map((entry) => compile(entry, needs));
	const head = ['// @ts-nocheck', ...header(entries)];
	const imports = importedTypes(entries);
	const helpers = await helpersFor(needs);
	const checks = compiled.map((result, index) => check(entries[index]!, result));
	const sections = [head.join('\n'), imports, helpers.join('\n\n'), checks.join('\n\n')];

	return `${sections.filter(Boolean).join('\n\n')}\n`;
}

function header(entries: ValidatorEntry[]): string[] {
	return [
		'// Generated by `bun run validators` from scripts/build/validators/registry.ts. Do not edit.',
		"// The checks are typebox's generated code with its Guard, Hashing and format helpers inlined,",
		'// so the client bundle imports no validator library. Those helpers keep the typebox MIT license.',
		`// Schemas: ${entries.map((entry) => entry.name).join(', ') || 'none'}`,
	];
}

function importedTypes(entries: ValidatorEntry[]): string {
	return [...new Set(entries.flatMap((entry) => entry.typeImports))].sort().join('\n');
}

async function helpersFor(needs: Needs): Promise<string[]> {
	const helpers: string[] = [];
	const formats = namespace('Formats', 'format', [...needs.formats].sort());
	const guard = namespace('Guard', 'guard', [...needs.guard].sort());
	const hashing = namespace('Hashing', 'hashing', [...needs.hashing].sort());

	for (const helper of [formats, guard, hashing, checkContext(needs.checkContext)]) {
		const source = await helper;

		if (source) {
			helpers.push(source);
		}
	}

	return helpers;
}

async function namespace(
	name: string,
	module: TypeboxModule,
	members: string[],
): Promise<string | undefined> {
	if (members.length === 0) {
		return undefined;
	}

	const { code, bindings } = await inlineExports(module, members);
	const returned = members.map((member, index) => `${member}: ${bindings[index]}`).join(', ');

	return `const ${name} = /* @__PURE__ */ (() => {\n${indent(code)}\n\n\treturn { ${returned} };\n})();`;
}

async function checkContext(needed: boolean): Promise<string | undefined> {
	if (!needed) {
		return undefined;
	}

	const { code, bindings } = await inlineExports('schema', ['CheckContext']);

	return `const CheckContext = /* @__PURE__ */ (() => {\n${indent(code)}\n\n\treturn ${bindings[0]};\n})();`;
}

function check(entry: ValidatorEntry, compiled: Compiled): string {
	const external = compiled.external.length
		? `\tconst External = [${compiled.external.join(', ')}];\n`
		: '';
	const returned = compiled.checkContext
		? `(value) => ${compiled.entry}(new CheckContext(), value)`
		: compiled.entry;

	return [
		`/** @description Whether \`value\` passes the \`${entry.name}\` check. */`,
		`export const ${entry.name}: (value: unknown) => value is ${entry.valueType} = /* @__PURE__ */ (() => {\n${external}${indent(compiled.body)}\n\n\treturn ${returned};\n})();`,
	].join('\n');
}

function compile(entry: ValidatorEntry, needs: Needs): Compiled {
	assertInlinable(entry.name, entry.schema);

	const { Code: code, External } = Code(entry.schema);
	const { body, checkContext } = split(entry.name, code);
	const external = External.variables.map((value) => serialize(entry.name, value, needs));

	needs.checkContext ||= checkContext;

	for (const match of body.matchAll(/\b(Guard|Hashing)\.(\w+)/g)) {
		const [, owner, member] = match;

		if (owner === 'Guard' && Object.hasOwn(Guard, member!)) {
			needs.guard.add(member!);
		} else if (owner === 'Hashing' && Object.hasOwn(Hashing, member!)) {
			needs.hashing.add(member!);
		} else {
			throw new Error(
				`${entry.name} needs typebox/${owner}.${member}, which is not a runtime helper.`,
			);
		}
	}

	return { body, entry: entryOf(entry.name, code), external, checkContext };
}

function split(name: string, code: string): Split {
	const body: string[] = [];
	let checkContext = false;

	for (const line of code.split('\n')) {
		const trimmed = line.trim();

		if (trimmed === '' || trimmed === '// @ts-ignore') {
			continue;
		}

		if (trimmed.startsWith('import ')) {
			checkContext ||= trimmed.includes('CheckContext');

			continue;
		}

		if (
			trimmed.startsWith('let External') ||
			trimmed.startsWith('export function SetExternal')
		) {
			continue;
		}

		if (trimmed.startsWith('export function Check')) {
			continue;
		}

		body.push(line);
	}

	if (body.length === 0) {
		throw new Error(`typebox compiled no check for ${name}.`);
	}

	return { body: body.join('\n'), checkContext };
}

function entryOf(name: string, code: string): string {
	const matched = /return (check_\d+)\(/.exec(code);

	if (!matched) {
		throw new Error(`typebox compiled no entry check for ${name}.`);
	}

	return matched[1]!;
}

const formatNames = new Map<unknown, string>(
	Format.Entries().map(([, check]) => [check, check.name]),
);

// UNKNOWN: an External variable is whatever value the schema registered, such as a regexp.
function serialize(name: string, value: unknown, needs: Needs): string {
	if (value instanceof RegExp) {
		return regexp(value);
	}

	if (typeof value === 'function') {
		const format = formatNames.get(value);

		if (format === undefined || format === '') {
			throw new Error(`${name} needs an external function that is not a registered format.`);
		}

		needs.formats.add(format);

		return `Formats.${format}`;
	}

	if (typeof value === 'bigint') {
		return `${value}n`;
	}

	if (typeof value === 'number' && !Number.isFinite(value)) {
		return String(value);
	}

	return serializable(name, value);
}

// UNKNOWN: walks an External's JSON shape; a function anywhere in it is refused, not flattened to `{}`.
function serializable(name: string, value: unknown, path = ''): string {
	if (typeof value === 'function') {
		throw new Error(
			`${name} needs an external function at ${path || '$'} that is not a format.`,
		);
	}

	if (typeof value === 'bigint') {
		throw new Error(
			`${name} needs an external bigint at ${path || '$'} that JSON cannot express.`,
		);
	}

	if (typeof value === 'number' && !Number.isFinite(value)) {
		throw new Error(
			`${name} needs an external number at ${path || '$'} that JSON cannot express.`,
		);
	}

	if (typeof value === 'object' && value !== null) {
		for (const [key, child] of Object.entries(value)) {
			serializable(name, child, path ? `${path}.${key}` : key);
		}
	}

	return JSON.stringify(value);
}

function regexp(value: RegExp): string {
	let source = '';
	let escaped = false;

	for (const character of value.source) {
		if (character === '/' && !escaped) {
			source += '\\/';
		} else {
			source += character;
		}

		escaped = character === '\\' ? !escaped : false;
	}

	return `/${source}/${value.flags}`;
}

function assertInlinable(name: string, schema: TSchema): void {
	const seen = new Set<object>();

	// UNKNOWN: walks the schema's JSON shape, where every node may be any value.
	function walk(node: unknown, path: string): void {
		if (typeof node !== 'object' || node === null || seen.has(node)) {
			return;
		}

		seen.add(node);

		if (Type.IsRefine(node)) {
			throw new Error(
				`${name} uses Type.Refine at ${path || '$'}, which Code cannot inline. Remove the refinement or keep the schema on zod.`,
			);
		}

		if (Type.IsCodec(node)) {
			throw new Error(
				`${name} uses Type.Codec at ${path || '$'}, which Code does not decode. Remove the codec or keep the schema on zod.`,
			);
		}

		if (Array.isArray(node)) {
			for (const [index, item] of node.entries()) {
				walk(item, `${path}[${index}]`);
			}

			return;
		}

		for (const [key, value] of Object.entries(node)) {
			walk(value, path ? `${path}.${key}` : key);
		}
	}

	walk(schema, '');
}

function indent(text: string): string {
	return text
		.split('\n')
		.map((line) => (line ? `\t${line}` : line))
		.join('\n');
}
