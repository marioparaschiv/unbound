function layerMarkup({
	fill,
	opacity,
	width: layerWidth = PIXEL,
	height: layerHeight = PIXEL,
	columns,
}: LogoLayer): string {
	const shapes = columns.split(';').flatMap((column) => {
		const [x, ...rows] = column.split(' ');

		return rows.map((row) => {
			const [y, height = layerHeight, width = layerWidth] = row.split(',');

			return `M${x} ${y}h${width}v${height}h-${width}z`;
		});
	});

	// One path per layer: react-native-svg mounts a native view per element, and the logo has 747 rectangles.
	// A layer's rectangles never overlap, so its fill opacity draws the same.
	return `<path fill="${fill}" fill-opacity="${opacity}" d="${shapes.join('')}"/>`;
}

/**
 * @description Builds the Unbound logo's SVG markup: the pixel mark with its colour fringes, and optionally
 * its drop shadow and scanlines, which muddy the mark at icon sizes.
 * @param textured Whether to draw the shadow and scanlines.
 * @returns The `<svg>` markup.
 */
export function buildLogoMarkup(textured = true): string {
	const layers = LOGO_LAYERS.filter((layer) => textured || !layer.texture);

	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${LOGO_VIEW_BOX}">${layers.map(layerMarkup).join('')}</svg>`;
}

export default buildLogoMarkup;
