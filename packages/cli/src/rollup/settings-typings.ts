function literalUnion(values: string[]): string {
	return values.length ? values.map((value) => JSON.stringify(value)).join(' | ') : 'never';
}

// An empty string means unset for a URL or an entity; an array leaves unset items out instead.
function stringType(displayAs: string, empty: boolean): string {
	const unset = empty ? " | ''" : '';

	switch (displayAs) {
		case 'color':
			return `${UTILS}.HexColor`;
		case 'url':
			return `${UTILS}.HttpUrl${unset}`;
		case 'emoji':
			return `${UTILS}.EmojiString`;
		case 'user':
		case 'channel':
		case 'guild':
		case 'role':
			return `${UTILS}.Snowflake${unset}`;
		default:
			return 'string';
	}
}

/**
 * @description Writes the TypeScript type a setting's value has, narrowed by its display.
 * @param field The setting.
 * @returns The type's source.
 */
export function settingType(field: SettingSchema): string {
	switch (field.kind) {
		case 'boolean':
			return 'boolean';
		case 'string':
			return stringType(field.displayAs, true);
		case 'choice':
			return literalUnion(field.options.map((choice) => choice.const));
		case 'array': {
			const element =
				field.of.kind === 'choice'
					? literalUnion(field.of.options.map((choice) => choice.const))
					: stringType(field.displayAs, false);

			return `(${element})[]`;
		}
		default:
			return 'number';
	}
}

function comment(
	labels: SettingCommon,
	messages: Record<string, string>,
	indent: string,
): string[] {
	const lines = [labels.title, labels.subtitle]
		.filter((key): key is string => key !== undefined)
		.map((key) => (messages[key] ?? key).replaceAll('*/', '*\\/').replaceAll('\n', ' '));

	if (!lines.length) {
		return [];
	}

	return [
		`${indent}/**`,
		...lines.flatMap((line, index) =>
			index ? [`${indent} *`, `${indent} * ${line}`] : [`${indent} * ${line}`],
		),
		`${indent} */`,
	];
}

function key(name: string): string {
	return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function isStored(node: SettingSchema | ButtonSchema): node is SettingSchema {
	return !isButton(node);
}

// The functions src/actions.ts exports, read from its types, so the typings never import its code.
const ACTION_NAME =
	'Extract<{ [K in keyof Actions]: Actions[K] extends () => void | Promise<void> ? K : never }[keyof Actions], string>';

/**
 * @description Writes the ambient typings of the builders and of a plugin's settings, each property documented with its en-US title and subtitle.
 * @param schema The plugin's validated settings schema.
 * @param messages The plugin's en-US messages.
 * @param hasActions Whether the plugin has a `src/actions.ts`, whose exports name `ActionName`.
 * @returns The `.d.ts` source.
 */
export function settingsTypings(
	schema: SettingsSchema,
	messages: Record<string, string>,
	hasActions = false,
): string {
	const shape: string[] = [];
	const paths: string[] = [];
	const booleans: string[] = [];

	function addField(path: string, name: string, field: SettingSchema, indent: string) {
		const type = settingType(field);

		shape.push(...comment(field, messages, indent), `${indent}${key(name)}: ${type};`);
		paths.push(...comment(field, messages, '\t\t'), `\t\t${JSON.stringify(path)}: ${type};`);

		if (field.kind === 'boolean') {
			booleans.push(JSON.stringify(path));
		}
	}

	for (const [name, node] of Object.entries(schema.properties)) {
		if (!isSettingsGroup(node)) {
			if (isStored(node)) {
				addField(name, name, node, '\t\t');
			}

			continue;
		}

		shape.push(...comment(node, messages, '\t\t'), `\t\treadonly ${key(name)}: {`);
		paths.push(
			...comment(node, messages, '\t\t'),
			`\t\t${JSON.stringify(name)}: Settings[${JSON.stringify(name)}];`,
		);

		for (const [child, field] of Object.entries(node.properties)) {
			if (isStored(field)) {
				addField(`${name}.${child}`, child, field, '\t\t\t');
			}
		}

		shape.push('\t\t};');
	}

	return [
		HEADER,
		'',
		SCHEMA_TYPINGS,
		'',
		`declare module '${SETTINGS_MODULE}' {`,
		REFINED_TYPES,
		'',
		"\t/** The plugin's settings: reads apply defaults, and writes are validated and saved to its Bucket. */",
		`\texport type Settings = {\n${shape.join('\n')}\n\t};`,
		'',
		'\t/** Each setting and section by its dot-separated key. */',
		`\ttype SettingValues = {\n${paths.join('\n')}\n\t};`,
		'',
		'\t/** Every setting and section by its dot-separated key; buttons are not settings. */',
		'\texport type SettingKey = keyof SettingValues;',
		'\t/** The value of the setting or section at `K`. */',
		'\texport type SettingsEntry<K extends SettingKey> = SettingValues[K];',
		'',
		'\t/** The functions src/actions.ts exports, which a `setting.button` can run. */',
		hasActions
			? `\ttype Actions = typeof import('./actions');\n\texport type ActionName = ${ACTION_NAME};`
			: '\texport type ActionName = never;',
		'',
		'\t/** The keys of the boolean settings, which `visibleWhen` and `disabledWhen` can name. */',
		`\texport type BooleanSettingKey = ${booleans.length ? booleans.join(' | ') : 'never'};`,
		'',
		"\t/** The plugin's settings. Assign a property, a section's too, to save it. */",
		'\texport const settings: Settings;',
		'\t/** Reads a setting or a whole section, and re-renders the component when it changes. */',
		'\texport function useSetting<K extends SettingKey>(key: K): SettingsEntry<K>;',
		'\t/** Puts every setting back to its default. */',
		'\texport function resetSettings(): void;',
		'\t/** The settings panel generated from settings.ts; a custom `getSettingsPanel` can render it too. */',
		"\texport function SettingsPanel(): import('react').ReactElement;",
		'}',
		'',
	].join('\n');
}

/**
 * @description Rewrites `src/unbound-settings.d.ts`, leaving the file alone when it is current.
 * @param pluginRoot The plugin's directory.
 * @param typings The `.d.ts` source from {@link settingsTypings}.
 * @returns Whether the file changed.
 */
export function writeSettingsTypings(pluginRoot: string, typings: string): boolean {
	const path = join(pluginRoot, SETTINGS_TYPINGS);

	if (existsSync(path) && readFileSync(path, 'utf8') === typings) {
		return false;
	}

	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, typings);

	return true;
}

export default { SETTINGS_TYPINGS, settingType, settingsTypings, writeSettingsTypings };
