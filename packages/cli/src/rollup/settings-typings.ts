/**
 * Where `ubd build` and `ubd dev` write the ambient typings of {@link SETTINGS_MODULE} and {@link SETTINGS_SCHEMA_MODULE}.
 * It sits in `src/`, which every plugin tsconfig includes, beside the `@unbound-app/i18n` typings.
 */
export const SETTINGS_TYPINGS = 'src/unbound-settings.d.ts';

const HEADER =
	'// Generated by ubd from settings.ts and i18n/en-US.json. Do not edit: `ubd build` and `ubd dev` rewrite it.';

// The display-refined string types, from the SDK's shared types so a plugin's own code can name the same ones.
const REFINED_TYPES = [
	'\t/** A `color` setting: `#RRGGBB`, or `#RRGGBBAA` with `alpha`. */',
	"\texport type HexColor = import('@unbound-app/api/types').HexColor;",
	'\t/** A `url` setting: an http or https URL. */',
	"\texport type HttpUrl = import('@unbound-app/api/types').HttpUrl;",
	'\t/** A Discord id, as an entity setting holds it. */',
	"\texport type Snowflake = import('@unbound-app/api/types').Snowflake;",
	"\t/** An `emoji` setting: a Unicode emoji or a custom emoji's name, then `:` and its id when custom. */",
	"\texport type EmojiString = import('@unbound-app/api/types').EmojiString;",
].join('\n');

const UTILS = `import('${SETTINGS_MODULE}')`;

