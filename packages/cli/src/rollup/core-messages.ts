import { parse, Type } from '@unbound-app/contracts/schema';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// The plugin build's ICU reader, so core's placeholder types match the ones it generates for plugins.
import { icuArgumentType, readIcuArguments, typeKey } from './icu-arguments.ts';

const ROOT = join(import.meta.dir, '..', '..', '..', '..');

/** Unbound's en-US file, every core key's source. */
export const CORE_SOURCE = join(ROOT, 'i18n', 'en-US.json');

/** Where the client's own `@unbound-app/i18n` typings live. */
export const CORE_TYPINGS = join(ROOT, 'packages', 'client', 'src', 'i18n', 'core-messages.d.ts');

/**
 * @description Writes the client's `@unbound-app/i18n` typings from Unbound's en-US file, shaped like a
 * plugin's generated ones: `MessageKey` for every key and `FormatVars` for each key with placeholders.
 * @param source The en-US messages.
 * @returns The `.d.ts` source.
 */
export function coreMessageTypings(source: Record<string, string>): string {
	const vars: string[] = [];

	for (const [key, message] of Object.entries(source)) {
		const found = readIcuArguments(message);

		if (!found.size) {
			continue;
		}

		const fields = [...found].map(
			([name, type]) => `${typeKey(name)}: ${icuArgumentType(type)}`,
		);

		vars.push(`\t\t${typeKey(key)}: { ${fields.join('; ')} };`);
	}

	return [
		'// Generated by packages/cli/src/rollup/core-messages.ts from i18n/en-US.json. Do not edit:',
		'// run `bun packages/cli/src/rollup/core-messages.ts`. A plugin build generates its own `@unbound-app/i18n`.',
		"declare module '@unbound-app/i18n' {",
		"\timport type enUS from '@i18n/en-US.json';",
		'',
		"\t/** Every key in Unbound's en-US file. */",
		'\texport type MessageKey = keyof typeof enUS;',
		'',
		'\t/** The placeholder values each message that has placeholders takes. */',
		`\texport type FormatVars = {\n${vars.join('\n')}\n\t};`,
		'}',
		'',
	].join('\n');
}

/**
 * @description Reads Unbound's en-US file, checking it maps every key to a string.
 * @returns The en-US messages.
 */
export function readCoreSource(): Record<string, string> {
	return parse(
		Type.Record(Type.String(), Type.String()),
		JSON.parse(readFileSync(CORE_SOURCE, 'utf8')),
	);
}

if (import.meta.main) {
	writeFileSync(CORE_TYPINGS, coreMessageTypings(readCoreSource()));
}
