export const API_MANIFEST = join(ROOT, 'packages', 'api', 'package.json');

/** The `@unbound-app/types` package. */
export const TYPES = join(ROOT, 'packages', 'types');

/** The `@unbound-app/types` index; its bundle feeds the `_internal` hoist file and the globals. */
