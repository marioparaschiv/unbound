/**
 * Policy for the plugin SDK generator that it cannot infer from the api barrel's `export * as`
 * specifiers (inlined libraries, surface roots, generated modules), and the locations derived from it.
 */

import { join, resolve, sep } from 'node:path';

type SdkConfig = {
	/**
	 * Packages whose typings are flattened into the bundle rather than becoming peers. `react`,
	 * `react-native` and `@types/react` are deliberately absent: they stay external peers.
	 */
	inlinedLibraries: string[];
	/** The public-surface root, relative to the repo root. Every `export * as` here becomes a module. */
	barrelPath: string;
	/**
	 * The client entry that assigns `window.unbound`, relative to the repo root. Its `UnboundLifecycle`
	 * type and the functions it names type the lifecycle members.
	 */
	entryPath: string;
	/** The directory the generated `.d.ts` tree is written to, relative to the repo root. */
	outDir: string;
	/**
	 * Modules a plugin's build generates, which the bundler cannot follow: each specifier, mapping a referenced name
	 * to its export. A module referencing one gets a type import of it.
	 */
	generatedModules: Record<string, Record<string, string>>;
};

export const config: SdkConfig = {
	inlinedLibraries: [
		'@unbound-app/types',
		'@unbound-app/discord-types',
		'@unbound-app/logger',
		'@unbound-app/utils',
		'possess',
	],
	barrelPath: 'packages/client/src/core/api.ts',
	entryPath: 'packages/client/src/core/index.ts',
	outDir: 'packages/api/src',
	generatedModules: {
		'@unbound-app/i18n': { MessageKey: 'MessageKey', MessageVars: 'FormatVars' },
	},
};

/**
 * @description Resolves the configured output directory and guards the generator's destructive
 * clean step: the resolved path must sit strictly inside the repository, so a misconfigured
 * `outDir` can never point `rmSync` at the repo root or anything outside it.
 * @param root The absolute repository root.
 * @param outDir The configured output directory, relative to the repository root.
 * @returns The validated absolute output directory.
 */
export function resolveOutDir(root: string, outDir: string): string {
	const resolved = resolve(root, outDir);

	if (resolved === root || !resolved.startsWith(root + sep)) {
		throw new Error(
			`config.outDir must resolve to a directory inside the repository, got '${resolved}'.`,
		);
	}

	return resolved;
}

