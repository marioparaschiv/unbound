export type ModuleEntry = {
	name: string;
	source: string;
	out: string;
	/** Top-level capability modules type `window.unbound.*`; nested subpaths live inside their parent. */
	topLevel: boolean;
};

/** The root `index.d.ts`, which only re-exports the top-level modules. */
export type RootEntry = {
	source: string;
	out: string;
};

export type SdkEntries = {
	root: RootEntry;
	/** Every module and nested subpath, sorted by name. */
	modules: ModuleEntry[];
};

/**
 * @description Computes the relative module specifier from a file at `fromOut` to a hoist file at
 * `toOut`, so nested modules (`metro/index.d.ts`) reach up to a top-level hoist file.
 * @param fromOut The absolute output path of the importing file.
 * @param toOut The absolute output path of the hoist file being imported.
 * @returns The POSIX-style relative module specifier, without extension.
 */
export function relativeSpecifier(fromOut: string, toOut: string): string {
	const rel = relative(dirname(fromOut), toOut)
		.replace(/\.d\.ts$/, '')
		.split('\\')
		.join('/');

	return rel.startsWith('.') ? rel : `./${rel}`;
}

/**
 * @description Resolves the configured output directory and guards the generator's destructive
 * clean step: the resolved path must sit strictly inside the repository, so a misconfigured
 * `outDir` can never point `rmSync` at the repo root or anything outside it.
 * @param root The absolute repository root.
 * @param outDir The configured output directory, relative to the repository root.
 * @returns The validated absolute output directory.
 */
export function resolveOutDir(root: string, outDir: string): string {
	const resolved = resolve(root, outDir);

	if (resolved === root || !resolved.startsWith(root + sep)) {
		throw new Error(
			`config.outDir must resolve to a directory inside the repository, got '${resolved}'.`,
		);
	}

	return resolved;
}

export type JsonValue = string | number | boolean | null | JsonValue[] | JsonObject;

export type JsonObject = { [key: string]: JsonValue };

/**
 * @description Narrows a JSON value to a plain object, excluding `null` and arrays.
 * @param value The JSON value to test.
 * @returns `true` when the value is a JSON object.
 */
export function isJsonObject(value: JsonValue | undefined): value is JsonObject {
	return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * @description Reads and parses a JSON object file, naming the file in the error so a malformed
 * or non-object manifest is attributable at a glance.
 * @param path The absolute path of the JSON file to read.
 * @returns The parsed object.
 */
export function readJson(path: string): JsonObject {
	let parsed: JsonValue;

	try {
		parsed = JSON.parse(readFileSync(path, 'utf8'));
	} catch (error) {
		throw new Error(`Failed to parse JSON from '${path}'.`, { cause: error });
	}

	if (!isJsonObject(parsed)) {
		throw new Error(`Expected a JSON object in '${path}'.`);
	}

	return parsed;
}
